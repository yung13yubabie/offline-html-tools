async function timeline(p,h){
 await nav(p,'cases');
 await p.locator('#newCase219').click();
 await p.locator('#caseTitle219').fill('合成案件日期順序');
 await p.locator('#caseClient219').selectOption('synthetic-a');
 await p.locator('#caseStart219').fill('2026-10-01');
 await p.locator('#caseDue219').fill('2026-11-30');
 await p.locator('#caseReminder219').check();
 await p.locator('#caseReminderDate219').fill('2026-11-10');
 await p.locator('#caseSave219').click();
 await p.locator('#caseForm219').waitFor({state:'detached'});
 const item=p.locator('[data-case-id219]'),toggle=item.locator('[data-record-toggle222]');
 await p.emulateMedia({reducedMotion:'no-preference'});
 const animationCount=async()=>item.evaluate(el=>{
  const button=el.querySelector('[data-record-toggle222]');
  button.click();
  return el.querySelector('.record-detail-body222').getAnimations({subtree:true}).length;
 });
 assert((await animationCount())>=3,'Expanded timeline should animate separate date nodes');
 assert.deepEqual(await item.locator('.record-timeline224 li div span').allTextContents(),['開始','提醒','截止']);
 await h.screenshot(p,'vat224-case-timeline-desktop');
 await toggle.click();
 await p.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await animationCount(),0);
 await p.setViewportSize({width:320,height:760});
 assert(await item.locator('.record-timeline224').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
 await h.screenshot(p,'vat224-case-timeline-mobile');
}
