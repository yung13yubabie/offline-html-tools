'use strict';
const assert=require('node:assert/strict');

async function accounting(p,{screenshot}){
 await p.locator('.nav-btn[data-view="accounting"]').click();
 const client=id=>p.locator(`[data-accounting-pc="2026-1::synthetic-${id}"]`);
 const section=key=>p.locator(`[data-account-focus="${key}"]`);
 const panel=key=>p.locator(`[data-acct-panel="${key}"]`);
 const search=p.locator('#accountingSearch'),status=p.locator('#accountingStatus223');
 assert.match(await p.locator('.accounting-detail-name').textContent(),/甲/);
 await client('a').focus();
 await client('a').press('Enter');
 assert.equal(await client('a').getAttribute('aria-pressed'),'true');
 await section('missing').click();
 assert.equal(await section('missing').getAttribute('aria-pressed'),'true');
 const row=panel('missing').locator('.acct-row-check').first();
 const batch=panel('missing').locator('[data-acct-batch-action="done"]');
 assert(await batch.isHidden());
 assert(await batch.isDisabled());
 await row.check();
 assert(await batch.isVisible());
 assert(await batch.isEnabled());
 await section('return').click();
 assert(await panel('missing').isHidden());
 assert(await panel('return').isVisible());
 await search.fill('TEST-B');
 assert.equal(await p.locator('[data-accounting-pc]').count(),1);
 assert.match(await p.locator('.accounting-detail-name').textContent(),/甲/);
 await section('missing').click();
 assert(await row.isChecked());
 assert.equal(await panel('missing').locator('.accounting-selection223').textContent(),'已選 1 筆');
 await search.fill('');
 await status.selectOption('done');
 assert.equal(await p.locator('[data-accounting-pc]').count(),0);
 assert(await row.isChecked());
 await status.selectOption('missing');
 await client('b').click();
 assert.match(await p.locator('.accounting-detail-name').textContent(),/乙/);
 assert(await panel('missing').isVisible());
 assert(!(await row.isChecked()));
 assert(await batch.isDisabled());
 await screenshot(p,'vat223-accounting-desktop');
 await p.setViewportSize({width:390,height:844});
 await p.locator('#accountingPicker223:not([open])').waitFor();
 await p.locator('#accountingPicker223 summary').click();
 await client('a').click();
 await p.locator('#accountingPicker223:not([open])').waitFor();
 assert(await panel('missing').isVisible());
 const edit=panel('missing').locator('[data-acct-edit]').first();
 assert(await edit.evaluate(button=>button.getBoundingClientRect().right<=innerWidth));
 await edit.click();
 await p.locator('#modalRoot .modal-foot').getByRole('button',{name:'取消',exact:true}).click();
 assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await screenshot(p,'vat223-accounting-mobile');
 await section('complete').click();
 assert.equal(await section('complete').innerText(),'結案檢核');
 assert.match(await p.locator('#accountingCompleteHint229').innerText(),/尚有 \d+ 筆待補，清零後可完成/);
 assert(await p.locator('#markAccountingCompleteBtn').isDisabled());
 await section('missing').click();
 const quick=panel('missing').locator('[data-acct-quick229]').first();
 await quick.click();
 await p.locator('.toast').filter({hasText:'已標記補齊'}).last().waitFor();
 assert.match(await panel('missing').locator('.accounting-row-status').first().innerText(),/已補/);
 const card=p.locator('#accountingStats [data-record-status227="done"]');
 await card.click();
 assert.equal(await status.inputValue(),'done');
 assert.equal(await card.getAttribute('aria-pressed'),'true');
}

async function notices(p,{screenshot,download}){
 await p.locator('.nav-btn[data-view="templates"]').click();
 const tab=key=>p.locator(`[data-template-tab="${key}"]`);
 const type=key=>p.locator(`#notificationTypeList [data-select-type="${key}"]`);
 const name=p.locator('#templateName'),body=p.locator('#templateText');
 const draft=p.locator('#templateDraft223'),context=p.locator('#noticeContextBar');
 const original=await name.inputValue();
 await name.fill('SYNTHETIC renamed draft');
 await body.fill('SYNTHETIC original draft {客戶}');
 assert(await draft.isVisible());
 await p.locator('#noticeMode').selectOption('merge');
 assert.match(await name.inputValue(),/renamed draft/);
 await type('dispatchReminder').click();
 assert(!(await draft.isVisible()));
 await type('receiptAsk').click();
 assert.match(await body.inputValue(),/original draft/);
 await tab('reminders').click();
 assert(await context.isHidden());
 assert(await p.locator('.notice-reminder-table229').isVisible());
 assert(await p.locator('#templateReminderList [data-edit-reminders]').count()>1);
 await p.locator('[data-edit-reminders="receiptAsk"]').click();
 const modal=p.locator('#modalRoot .modal'),add=modal.locator('#addTplReminder'),rows=modal.locator('.rem-row');
 await modal.locator('#tplReminderEnabled').check();
 await add.click();
 await rows.first().locator('.rem-days').fill('4');
 await add.click();
 const fixed=rows.last();
 await fixed.locator('.rem-mode').selectOption('fixed');
 assert.equal(await rows.first().locator('.rem-days').inputValue(),'4');
 await modal.getByRole('button',{name:'儲存',exact:true}).click();
 assert.match(await modal.locator('#templateReminderError223').textContent(),/固定提醒日期/);
 await fixed.locator('.rem-date').fill('2026-11-20');
 await add.click();
 await rows.last().locator('.rem-del').click();
 assert.equal(await fixed.locator('.rem-date').inputValue(),'2026-11-20');
 await modal.getByRole('button',{name:'儲存',exact:true}).click();
 await p.locator('#modalRoot.show').waitFor({state:'hidden'});
 const toggle=p.locator('[data-reminder-toggle229="receiptAsk"]');
 assert(await toggle.isChecked());
 await toggle.uncheck();
 await p.waitForFunction(()=>document.querySelector('[data-reminder-toggle229="receiptAsk"]').closest('tr').textContent.includes('未加入'));
 await toggle.check();
 await p.waitForFunction(()=>document.querySelector('[data-reminder-toggle229="receiptAsk"]').closest('tr').textContent.includes('已加入'));

 await tab('manage').click();
 assert.match(await body.inputValue(),/original draft/);
 await p.locator('#templateActions223 summary').click();
 await p.locator('#discardTemplate223').click();
 assert.equal(await name.inputValue(),original);
 assert(await draft.isHidden());
 await p.locator('#noticeMode').selectOption('single');
 await body.fill('SYNTHETIC saved work {客戶}');
 await p.locator('#saveTemplateBtn').click();
 await p.locator('.toast').filter({hasText:'模板已儲存'}).last().waitFor();
 assert(await draft.isHidden());
 await screenshot(p,'vat223-templates-desktop');

 await tab('export').click();
 assert(await context.isHidden());
 await p.locator('#exportTemplateClearBtn').click();
 await p.locator('.txt-template-choice[value="receiptAsk"]').check();
 const alpha=p.locator('#exportClients223 input[value="2026-1::synthetic-a"]');
 const beta=p.locator('#exportClients223 input[value="2026-1::synthetic-b"]');
 await alpha.check();
 assert(!(await beta.isChecked()));
 assert.match(await p.locator('#exportTemplateSummary').textContent(),/1 位客戶/);
 const file=await download(p,()=>p.locator('#exportTxtBtn').click());
 assert.match(file.toString(),/SYNTHETIC saved work 合成測試客戶甲/);
 assert(!file.toString().includes('合成測試客戶乙'));
 await p.locator('#txtSelectAllBtn').click();
 assert(await beta.isChecked());
 await p.locator('#txtClientSearch').fill('TEST-B');
 assert.equal(await p.locator('#exportClients223 input').count(),1);
 assert(await beta.isChecked());
 assert.match(await p.locator('#exportTemplateSummary').textContent(),/1 位客戶/);
 await p.locator('#txtClearBtn').click();
 assert(!(await beta.isChecked()));
 await screenshot(p,'vat223-export-desktop');

 for(const width of [390,320]){
  await p.setViewportSize({width,height:844});
  await tab('manage').click();
  await p.locator('#noticeLibrary223:not([open])').waitFor();
  assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await p.locator('[data-notice-compose="preview"]').click();
  assert(await p.locator('#templatePreview').isVisible());
  await p.locator('[data-notice-compose="write"]').click();
  assert.match(await body.inputValue(),/saved work/);
  await tab('export').click();
  assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 }
 await p.setViewportSize({width:390,height:844});
 await tab('manage').click();
 await screenshot(p,'vat223-templates-mobile');
}

module.exports={accounting,notices};
